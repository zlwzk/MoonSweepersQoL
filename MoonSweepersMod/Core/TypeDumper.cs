using System;
using System.IO;
using System.Text;
using Il2CppSystem;

namespace MoonSweepersMod.Core
{
    /// <summary>
    /// Dumps every loaded IL2CPP type to a text file. This is the discovery tool
    /// that lets us (and the user) learn the game's real internal type/method
    /// names so the gameplay hooks can be finalised without guesswork.
    /// </summary>
    public static class TypeDumper
    {
        public static void Dump(string path)
        {
            try
            {
                var asm = Il2CppSystem.Reflection.Assembly.GetExecutingAssembly();
                var sb = new StringBuilder();
                sb.AppendLine("# Moon Sweepers IL2CPP type dump @ " + DateTime.Now);
                sb.AppendLine("# Generated by Moon Sweepers QoL mod. Use this to wire up gameplay hooks.");
                if (asm == null) { sb.AppendLine("(no executing assembly captured)"); }
                else
                {
                    var types = asm.GetTypes();
                    sb.AppendLine("Assembly: " + (asm.FullName ?? "?") + "  Types: " + (types?.Length ?? 0));
                    if (types != null)
                    {
                        Array.Sort(types, (a, b) => string.Compare(a.FullName, b.FullName, StringComparison.Ordinal));
                        foreach (var t in types)
                            sb.AppendLine((t.FullName ?? t.Name) + "  :  " + (t.BaseType?.FullName ?? "?"));
                    }
                }
                Directory.CreateDirectory(Path.GetDirectoryName(path) ?? ".");
                File.WriteAllText(path, sb.ToString());
                Log.Info("[TypeDumper] Wrote " + (asm?.GetTypes()?.Length ?? 0) + " types -> " + path);
            }
            catch (Exception e) { Log.Error("[TypeDumper] " + e); }
        }
    }
}
